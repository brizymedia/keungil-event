    /** 전국 도시 — 「다른 지역 글」인지 가려내는 데 쓴다 */
    val ALL_CITIES: List<String> by lazy { REGIONS.flatMap { it.cities } }

    /** 판단 결과. 왜 울렸는지(또는 왜 안 울렸는지) 같이 돌려준다. */
    data class Verdict(
        val hit: Boolean,
        val reason: String,
        val signals: List<String> = emptyList(),
        val jobs: List<String> = emptyList(),
        val places: List<String> = emptyList()
    )

    private fun found(text: String, words: List<String>): List<String> {
        val lower = text.lowercase()
        return words.filter { lower.contains(it.lowercase()) }
    }

    /**
     * @param jobWords  고른 직군의 단어를 합친 것
     * @param myCities  고른 권역의 도시. 비어 있으면 지역을 안 가린다.
     */
    fun judge(text: String, jobWords: List<String>, myCities: List<String>): Verdict {
        if (text.isBlank()) return Verdict(false, "빈 글")
        if (jobWords.isEmpty()) return Verdict(false, "직군 미선택")

        if (text.count { it == '#' } >= 3) return Verdict(false, "광고 도배")

        val bad = found(text, EXCLUDE)
        if (bad.isNotEmpty()) return Verdict(false, "제외어: " + bad.first())

        val clean = deStuck(text)

        val sig = found(clean, SIGNAL)
        if (sig.isEmpty()) return Verdict(false, "구인 신호어 없음")

        val job = found(clean, jobWords)
        if (job.isEmpty()) return Verdict(false, "직군어 없음")

        if (myCities.isNotEmpty()) {
            val mine = found(text, myCities)
            if (mine.isEmpty()) {
                // 지역이 아예 안 적힌 글은 놓치는 게 아까워서 통과시킨다
                val elsewhere = found(text, ALL_CITIES)
                if (elsewhere.isNotEmpty()) return Verdict(false, "다른 지역: " + elsewhere.first())
            }
            return Verdict(true, "울림", sig, job, mine)
        }

        return Verdict(true, "울림", sig, job, found(text, ALL_CITIES))
    }

    /** 알림 제목에 쓸 짧은 말 — 무슨 일감인지 한눈에 */
    fun summary(v: Verdict): String {
        val place = v.places.firstOrNull()
        val job = v.jobs.firstOrNull() ?: "행사"
        return if (place != null) "$place · $job" else job
    }
