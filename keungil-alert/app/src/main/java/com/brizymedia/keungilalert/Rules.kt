    /** 붙어버린 말을 공백으로 바꿔 없앤다 */
    private fun deStuck(text: String): String {
        var t = text
        for (w in STUCK) if (t.contains(w, ignoreCase = true)) t = t.replace(w, " ", ignoreCase = true)
        return t
    }

