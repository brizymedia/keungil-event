/**
 * 네이버 블로그용 원고 검사 — scripts/blog-check.mjs 가 불러 쓴다.
 *
 * 홈페이지 글을 그대로 네이버에 올리면 네이버가 유사문서로 걸러 한쪽이 검색에서 빠진다.
 * 그래서 ① 원글과 많이 겹치면 막고, ② 원글에 없는 숫자 · 약속 · 지역 이야기를 새로 만들면 막는다.
 * 원고 형식은 _blog/GUIDE.md 9장.
 */
import { 본문글, 글이미지들 } from './build-blog.mjs';
import { 네이버읽기, 네이버문단들, 네이버사진들, 네이버글 } from './build-naver.mjs';

export function 네이버검사(도구) {
  const { ROOT, posts, 지역, 사진, 금지, 없는품목, 약속말, 문장들, 글자수, 붙여, 정규식글자, 지역이름들, 조각만들기, 겹침, 오류, 경고, 새네이버 } = 도구;
  const 원고들 = 네이버읽기(ROOT);
  const 검사대상 = 원고들.filter((n) => (새네이버 ? 새네이버.has(n._파일) : true));
  if (새네이버 && 검사대상.length !== 새네이버.size) {
    오류.push(`✗ --new 로 준 파일 중 _blog/naver 에 없는 것이 있다: ${[...새네이버].join(', ')}`);
  }

  for (const n of 검사대상) {
    const 틀림 = (m) => 오류.push(`✗ naver/${n._파일}: ${m}`);
    const 주의 = (m) => 경고.push(`△ naver/${n._파일}: ${m}`);
    const 원글 = posts.find((p) => p._파일 === n._파일);
    if (!원글) { 틀림(`같은 이름의 홈페이지 글(_blog/posts/${n._파일})이 없다 — 네이버 원고는 원글과 파일 이름이 같아야 한다`); continue; }
    if (!Array.isArray(n.본문) || !n.본문.length) { 틀림('본문 배열이 없다 — 문단은 글자, 사진은 { "사진": 경로, "설명": 캡션 }'); continue; }
    if (n.본문.some((x) => typeof x !== 'string' && !(x && typeof x === 'object' && x.사진))) {
      틀림('본문 항목은 문단(글자)이거나 { "사진": 경로, "설명": 캡션 } 이어야 한다');
      continue;
    }

    const r = 지역.get(원글.region);
    const 문단 = 네이버문단들(n);
    const 사진들 = 네이버사진들(n);
    const 글 = 네이버글(n);

    /* 형식 */
    if (n.날짜 !== 원글.date) 틀림(`날짜는 원글과 같아야 한다(${원글.date})`);
    if (글자수(n.제목) < 12 || 글자수(n.제목) > 40) 틀림(`제목은 12~40자 (지금 ${글자수(n.제목)})`);
    if (n.제목 === 원글.title) 틀림('제목이 홈페이지 글과 똑같다 — 네이버용 제목은 새로 짓는다');
    if (r && 원글.region !== 'common' && !String(n.제목).includes(r.이름)) 틀림(`제목에 지역 이름(${r.이름})이 없다`);
    if (!붙여(n.제목).includes(붙여(원글.keyword.main))) 틀림(`제목에 핵심 키워드 '${원글.keyword.main}' 가 없다`);
    if (문단.length < 6) 틀림(`문단은 6개 이상 (지금 ${문단.length}) — 네이버는 짧은 문단이 읽힌다`);
    문단.forEach((t, i) => { if (글자수(t) > 300) 틀림(`문단[${i}] 이 길다(${글자수(t)}자) — 300자 이하로 나눈다`); });
    const 길이 = 글자수(문단.join('\n'));
    if (길이 < 700) 틀림(`본문이 짧다 (${길이}자, 700자 이상)`);
    else if (길이 > 2500) 주의(`본문 ${길이}자 — 네이버는 2500자 안쪽이 읽기 좋다`);

    const 원문 = JSON.stringify(n);
    if (/\[[^\]]+\]\([^)\s]*\)/.test(원문)) 틀림('네이버 에디터는 [글](주소) 링크를 못 쓴다 — 홈페이지 링크는 페이지가 자동으로 붙인다');
    if (/\*\*/.test(원문)) 틀림('**굵게** 표시는 네이버에서 글자 그대로 보인다 — 쓰지 않는다');
    if (/^#|\n#/.test(원문)) 틀림('# 소제목 표시는 쓰지 않는다 — 문단으로 나눈다');

    /* 사진 — 목록에 있는 것만, 찍은 곳을 바꾸지 않는다 */
    if (사진들.length < 2) 틀림('사진은 2장 이상 넣는다');
    const 묶음 = new Set();
    for (const s of 사진들) {
      const 정보 = 사진.get(s.사진);
      if (!정보) { 틀림(`사진 ${s.사진} 은 _blog/photos.json 에 없다`); continue; }
      if (정보.제외) { 틀림(`사진 ${s.사진} 은 쓰지 않는 사진 — ${정보.제외}`); continue; }
      if (묶음.has(정보.묶음번호)) 틀림(`사진 ${s.사진} — 같은 장면 묶음의 사진을 두 장 썼다`);
      묶음.add(정보.묶음번호);
      if (글자수(s.설명) < 8 || 글자수(s.설명) > 120) 틀림(`사진 ${s.사진} 설명은 8~120자`);
      for (const w of 지역이름들.filter((x) => String(s.설명).includes(x))) {
        if (정보.지역 !== w && !String(정보.행사 || '').includes(w)) {
          틀림(`사진 ${s.사진} 설명에 '${w}' — 목록상 이 사진의 지역은 '${정보.지역 || '모름'}'. 찍은 곳을 바꿔 쓰지 않는다`);
        }
      }
    }
    const 원글사진 = new Set(글이미지들(원글).map((im) => im.path));
    if (사진들.length && 사진들.every((s) => 원글사진.has(s.사진))) 주의('홈페이지 글과 사진이 모두 같다 — 다른 컷을 한 장이라도 넣으면 좋다');

    /* 태그 */
    if (!Array.isArray(n.태그) || n.태그.length < 3 || n.태그.length > 10) 틀림('태그는 3~10개');
    else {
      if (new Set(n.태그).size !== n.태그.length) 틀림('태그가 겹친다');
      n.태그.forEach((t) => { if (/^#/.test(t) || 글자수(t) < 2 || 글자수(t) > 20) 틀림(`태그 '${t}' — # 없이 2~20자`); });
    }

    /* 홈페이지 글과 같은 금지 규칙 */
    for (const [식, 이유] of 금지) { const m = 글.match(식); if (m) 틀림(`${이유} — "${m[0]}"`); }
    for (const 문장 of 문장들(글)) {
      const 품목 = 없는품목.find((w) => 문장.includes(w));
      if (품목 && 약속말.test(문장)) 틀림(`견적서에 없는 '${품목}' 을 빌려준다고 약속했다 — "${문장.slice(0, 60)}…"`);
    }
    if (r && 원글.region !== 'common') {
      for (const 동네 of r.동네 || []) {
        const 식 = new RegExp(`${정규식글자(동네)}[^.!?\\n]{0,20}(처럼|같은|같이)|${정규식글자(동네)}\\s*(인근|근처|일대|주변|쪽)\\s*(은|는|처럼|의|에서는)`);
        const m = 글.match(식);
        if (m) 틀림(`동네 '${동네}' 에 특징을 붙인 문장 — 동네 이름은 괄호 속 나열로만 쓴다: "${m[0]}"`);
      }
      const 지역말 = [r.이름, ...(r.동네 || [])];
      for (const 문장 of 문장들(글)) {
        if (지역말.some((w) => 문장.includes(w)) && /(경우[가도]|문의[가도]|요청[이도]|찾는\s*분[이도])\s*(흔|잦|많)/.test(문장)) {
          틀림(`지역 문의 · 요청이 흔하다는 통계를 지어낸 문장 — "${문장.slice(0, 60)}…"`);
        }
      }
    }

    /* 원글에 없는 숫자를 새로 만들지 않는다 — 네이버 원고는 원글에 쓴 사실만 다시 쓴 것이다 */
    const 원글글자 = 붙여([본문글(원글), 원글.title, 원글.description, ...글이미지들(원글).map((im) => `${im.alt} ${im.caption}`)].join(' '));
    const 숫자들 = new Set((글.replace(/1533-?7295/g, '').match(/\d[\d.,]*/g) || []).map((x) => x.replace(/[.,]+$/, '')));
    for (const 숫자 of 숫자들) {
      if (!원글글자.includes(숫자)) 틀림(`숫자 '${숫자}' 가 홈페이지 원글에 없다 — 네이버 원고에 새 숫자를 만들지 않는다`);
    }

    /* 겹침 — 이게 이 검사의 핵심이다 */
    const 조각 = 조각만들기(글);
    const v = 겹침(조각, 조각만들기(본문글(원글)));
    if (v > 0.25) 틀림(`홈페이지 원글과 ${(v * 100).toFixed(0)}% 겹친다 — 네이버가 유사문서로 걸러 한쪽이 검색에서 빠진다. 도입부터 새로 쓴다`);
    else if (v > 0.18) 주의(`홈페이지 원글과 ${(v * 100).toFixed(0)}% 겹친다`);
    for (const o of 원고들) {
      if (o === n) continue;
      const w = 겹침(조각, 조각만들기(네이버글(o)));
      if (w > 0.25) 틀림(`네이버 원고 naver/${o._파일} 와 ${(w * 100).toFixed(0)}% 겹친다`);
    }
  }

  return { 검사수: 검사대상.length };
}
